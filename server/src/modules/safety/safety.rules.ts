/** 归一化：全角→半角、繁体→简体、去空白、统一常见标点 */
export function normalizeSafetyText(input: string): string {
  if (!input) return '';
  const half = input
    .replace(/[\uFF01-\uFF5E]/g, (ch) => String.fromCharCode(ch.charCodeAt(0) - 0xfee0))
    .replace(/\u3000/g, ' ')
    .replace(/\s+/g, '')
    .replace(/[，、；]/g, '，')
    .replace(/[。！？]/g, '。')
    .replace(/[（）()~～]/g, '')
    .toLowerCase();
  return half.replace(/[\u4E00-\u9FA5]/g, (ch) => T2S[ch] ?? ch);
}

