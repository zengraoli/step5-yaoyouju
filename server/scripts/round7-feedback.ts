function hitRules(text: string): string[] {
  return RED_FLAG_RULES.filter((r) => matchesRedFlagRule(r, text)).map((r) => r.code);
}

let fail = 0;
const report = (title: string, cases: string[], expect: (t: string) => boolean, note: (t: string) => string) => {
  console.log(`\n== ${title} ==`);
  let ok = 0;
  for (const t of cases) {
    const pass = expect(t);
    if (!pass) {
      fail += 1;
      console.log(`  ✗ ${t}  → ${note(t)}`);
    } else ok += 1;
  }
  console.log(`  通过 ${ok}/${cases.length}`);
};

report('第1条 应触发', ITEM1_TRIGGER, (t) => hitRules(t).length > 0, (t) => hitRules(t).join(',') || '未命中');
report('第2条 应触发', ITEM2_TRIGGER, (t) => hitRules(t).length > 0, (t) => hitRules(t).join(',') || '未命中');
report('第3条 高危误判（应不命中）', ITEM3_NOT_HIGH, (t) => hitRules(t).length === 0, (t) => hitRules(t).join(','));
report('第3条 中危误判（应不命中）', ITEM3_NOT_MEDIUM, (t) => hitRules(t).length === 0, (t) => hitRules(t).join(','));
report(
  '第9条 越界应拒答',
  ITEM9_OUT_OF_SCOPE,
  (t) => OUT_OF_SCOPE_RULES.some((r) => matchesScopeRule(r, t)),
  () => '未拒答',
);

console.log(`\n合计不达标：${fail}`);
process.exit(fail === 0 ? 0 : 1);
